CREATE DEFINER=`root`@`%` TRIGGER `T_PNR_BU_DOCF` BEFORE UPDATE ON `pnr` FOR EACH ROW BEGIN
DECLARE D_DOCFINMOV_SP VARCHAR(120) DEFAULT ''; 
DECLARE D_DIT_CODICE VARCHAR(4) DEFAULT ''; 	
DECLARE D_UTN_CODICE VARCHAR(8) DEFAULT ''; 	
	
SET D_UTN_CODICE=LEFT(USER(),LOCATE('@',USER())-1);

SELECT  UTN.DIT_CODICE 
FROM ARC.UTN
WHERE UTN.CODICE=D_UTN_CODICE
INTO D_DIT_CODICE; 

SELECT DOCFINMOV_SP
FROM TDOCF
WHERE TDOCF.codice=D_DIT_CODICE
into D_DOCFINMOV_SP;
	
IF NEW.CFG_TIPO = 'G' THEN
	IF D_DOCFINMOV_SP='' THEN     
		IF NEW.IMPORTO_DARE_EURO <> 0 THEN
   		CALL P_DOCFINMOV('U',NEW.PROGRESSIVO,NEW.RIGA,NEW.CFG_CODICE,NEW.IMPORTO_DARE_EURO );
	   ELSE
	      CALL P_DOCFINMOV('U',NEW.PROGRESSIVO,NEW.RIGA,NEW.CFG_CODICE,NEW.IMPORTO_AVERE_EURO );
   	END IF;
   ELSEIF D_DOCFINMOV_SP='P_DOCFINMOV_SP' THEN     
	   IF NEW.IMPORTO_DARE_EURO <> 0 THEN
   		CALL P_DOCFINMOV_SP('U',NEW.PROGRESSIVO,NEW.RIGA,NEW.CFG_CODICE,NEW.IMPORTO_DARE_EURO );
	   ELSE
	      CALL P_DOCFINMOV_SP('U',NEW.PROGRESSIVO,NEW.RIGA,NEW.CFG_CODICE,NEW.IMPORTO_AVERE_EURO );
   	END IF;
	END IF;
		   	   
END IF;
END 

