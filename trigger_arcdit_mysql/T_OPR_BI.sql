CREATE TRIGGER T_OPR_BI_0
  BEFORE INSERT
  ON `opr`
  FOR EACH ROW
BEGIN 


IF NEW.PROGRESSIVO = 0 THEN
  CALL P_CAMPO_VUOTO('opr','progressivo');
END IF;

IF NEW.RIGA = 0 THEN
  CALL P_CAMPO_VUOTO('opr','riga');
END IF;

IF NEW.SEQUENZA = 0 THEN
  SET NEW.SEQUENZA = NEW.RIGA;
END IF;

IF NEW.ID IS NOT NULL THEN
  SET NEW.ID = null;
END IF;

END
